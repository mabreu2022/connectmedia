CREATE TABLE TB_ASSUNTOS (
    ID_ASSUNTO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE TB_CANAIS (
    ID_CANAL INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_CANAL VARCHAR(150) NOT NULL,
    URL_YOUTUBE VARCHAR(255) NOT NULL UNIQUE,
    ATIVO SMALLINT DEFAULT 1
);

CREATE TABLE TB_CANAL_ASSUNTO (
    ID_CANAL INTEGER NOT NULL,
    ID_ASSUNTO INTEGER NOT NULL,
    PALAVRA_CHAVE VARCHAR(100) NOT NULL,
    CONSTRAINT PK_CANAL_ASSUNTO PRIMARY KEY (ID_CANAL, ID_ASSUNTO),
    CONSTRAINT FK_VINCULO_CANAL FOREIGN KEY (ID_CANAL) REFERENCES TB_CANAIS (ID_CANAL) ON DELETE CASCADE,
    CONSTRAINT FK_VINCULO_ASSUNTO FOREIGN KEY (ID_ASSUNTO) REFERENCES TB_ASSUNTOS (ID_ASSUNTO) ON DELETE CASCADE
);

CREATE TABLE TB_VIDEOS_BIBLIOTECA (
    ID_VIDEO INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CANAL INTEGER NOT NULL,
    ID_ASSUNTO INTEGER,
    TITULO_VIDEO VARCHAR(255) NOT NULL,
    URL_VIDEO VARCHAR(255) NOT NULL UNIQUE,
    THUMBNAIL_URL VARCHAR(500),
    STATUS_DOWNLOAD VARCHAR(20) DEFAULT 'PENDENTE',
    CAMINHO_ARQUIVO VARCHAR(500),
    PROGRESSO INTEGER DEFAULT 0,
    DATA_PUBLICACAO TIMESTAMP,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_VIDEO_CANAL FOREIGN KEY (ID_CANAL) REFERENCES TB_CANAIS (ID_CANAL)
);

CREATE TABLE TB_CONFIGURACOES (
    ID_CONFIG INTEGER NOT NULL PRIMARY KEY,
    CAMINHO_DOWNLOADS VARCHAR(500),
    QTD_VIDEOS_BUSCA INTEGER DEFAULT 5,
    INTERVALO_MINUTOS INTEGER DEFAULT 60,
    DATA_INICIAL DATE,
    DATA_FINAL DATE,
    BUSCAR_VIDEOS SMALLINT DEFAULT 1,
    BUSCAR_SHORTS SMALLINT DEFAULT 1,
    BUSCAR_LIVES SMALLINT DEFAULT 1
);

